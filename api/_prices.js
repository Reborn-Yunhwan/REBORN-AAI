// 매칭 실패 시 제조사별 폴백 (단가표상 '기타 모델' 행)
const FALLBACK = { '삼성': 1000, '애플': 1000, 'LG': 1000 };

// ── 정규화 ──────────────────────────────────────────────

// 모델번호 정규화
//  삼성: SM-S938N / SM-S938K / SM-S938S / SM-S938L → SM-S938 (통신사 접미사 제거)
//  애플: A3526 그대로
function normModelNo(v){
  if(!v) return '';
  var s = String(v).toUpperCase().replace(/\s+/g,'').replace(/[^A-Z0-9-]/g,'');
  // 삼성 통신사 접미사 제거 (SM-으로 시작 + 끝이 N/K/S/L/B/U/F/0)
  var m = s.match(/^(SM-[A-Z]?[0-9]{3,4})[A-Z0-9]?$/);
  if(m) return m[1];
  return s;
}

// 용량 정규화: 256GB / 256기가 / 256 → 256G,  1TB / 1T → 1TB
function normCap(v){
  if(!v) return '';
  var s = String(v).toUpperCase().replace(/\s+/g,'').replace(/기가/g,'G').replace(/테라/g,'TB');
  var t = s.match(/([0-9]+)\s*T/);
  if(t) return t[1] + 'TB';
  var g = s.match(/([0-9]+)\s*G/);
  if(g) return g[1] + 'G';
  var n = s.match(/^([0-9]+)$/);
  if(n) return n[1] + 'G';
  return s;
}

// 펫네임 정규화: 공백/대소문자/특수문자 제거 후 비교용
//  '갤럭시 S25 Ultra' / '갤럭시S25울트라' 를 같게 만들기 위한 한/영 표기 통일 포함
function normPet(v){
  if(!v) return '';
  var s = String(v).toUpperCase();
  s = s.replace(/GALAXY/g,'갤럭시').replace(/IPHONE/g,'아이폰');
  s = s.replace(/ULTRA/g,'울트라').replace(/PLUS/g,'플러스').replace(/PRO\s*MAX/g,'프로맥스');
  s = s.replace(/PRO/g,'프로').replace(/MINI/g,'미니').replace(/AIR/g,'에어').replace(/EDGE/g,'엣지');
  s = s.replace(/FOLD/g,'폴드').replace(/FLIP/g,'플립');
  // '+' 는 반드시 특수문자 제거 '전에' 치환해야 한다.
  // (먼저 제거하면 '아이폰 15+' 가 '아이폰15' 가 되어 일반 아이폰15와 충돌)
  s = s.replace(/\+/g,'플러스');
  s = s.replace(/[^0-9A-Z가-힣]/g,'');
  return s;
}

function toObj(row, matchType){
  return {
    modelNo: row[0],
    storage: row[1],
    petName: row[2],
    stdPetName: row[3],
    prices: {
      'Excellent':  row[4],
      'Very Good':  row[5],
      'Good':       row[6],
      'Normal':     row[7],
      'Bad':        row[8]
    },
    matchType: matchType,
    priceVersion: PRICE_VERSION
  };
}

// ── 단가 조회 ────────────────────────────────────────────
// 우선순위: ① 모델번호+용량 정확  ② 모델번호만  ③ 펫네임+용량  ④ 펫네임만  ⑤ 제조사 폴백
export function lookupPrice(modelNo, storage, modelName, maker){
  var mn  = normModelNo(modelNo);
  var cap = normCap(storage);
  var pet = normPet(modelName);

  // ① 모델번호 + 용량 정확매칭
  if(mn && cap){
    for(var i=0;i<ROWS.length;i++){
      if(ROWS[i][0] === mn && ROWS[i][1] === cap) return toObj(ROWS[i],'exact');
    }
  }

  // ② 모델번호만 매칭 → 해당 모델의 최저용량 행 (보수적)
  if(mn){
    var cands = ROWS.filter(function(r){ return r[0] === mn; });
    if(cands.length){
      // 용량 오름차순 정렬 후 첫 행
      cands.sort(function(a,b){ return capBytes(a[1]) - capBytes(b[1]); });
      return toObj(cands[0], 'model_only');
    }
  }

  // ③ 펫네임 + 용량
  if(pet && cap){
    for(var j=0;j<ROWS.length;j++){
      if(ROWS[j][1] !== cap) continue;
      var p1 = normPet(ROWS[j][2]), p2 = normPet(ROWS[j][3]);
      if(p1 === pet || p2 === pet) return toObj(ROWS[j],'petname');
    }
  }

  // ④ 펫네임만 (부분일치는 가장 긴 것 우선 — '아이폰17'이 '아이폰17프로'를 먹지 않도록)
  if(pet){
    var best = null, bestLen = 0;
    for(var k=0;k<ROWS.length;k++){
      var q1 = normPet(ROWS[k][2]), q2 = normPet(ROWS[k][3]);
      [q1,q2].forEach(function(q){
        if(!q) return;
        if(pet === q || pet.indexOf(q) >= 0){
          if(q.length > bestLen){ bestLen = q.length; best = ROWS[k]; }
        }
      });
    }
    if(best) return toObj(best,'petname_partial');
  }

  // ⑤ 제조사 폴백
  var mk = maker || guessMaker(mn, pet);
  if(mk && FALLBACK[mk] != null){
    var v = FALLBACK[mk];
    return {
      modelNo: mn || null, storage: cap || null,
      petName: mk + ' 기타 모델', stdPetName: mk + ' 기타 모델',
      prices: {'Excellent':v,'Very Good':v,'Good':v,'Normal':v,'Bad':v},
      matchType: 'fallback', priceVersion: PRICE_VERSION
    };
  }

  return null;
}

function capBytes(c){
  var t = c.match(/^([0-9]+)TB$/); if(t) return parseInt(t[1],10) * 1024;
  var g = c.match(/^([0-9]+)G$/);  if(g) return parseInt(g[1],10);
  return 999999;
}

function guessMaker(mn, pet){
  if(mn.indexOf('SM-') === 0) return '삼성';
  if(/^A[0-9]{4}$/.test(mn)) return '애플';
  if(pet.indexOf('갤럭시') >= 0) return '삼성';
  if(pet.indexOf('아이폰') >= 0) return '애플';
  if(pet.indexOf('LG') >= 0 || pet.indexOf('벨벳') >= 0 || pet.indexOf('윙') >= 0) return 'LG';
  return null;
}

export default { lookupPrice, PRICE_VERSION, GRADE_ORDER };
